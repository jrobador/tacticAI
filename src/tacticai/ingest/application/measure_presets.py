"""Measurement gate: run headless matches per preset, aggregate style/shape metrics for the home team."""
import json
import os
import tempfile
from multiprocessing import Pool
from statistics import mean, pstdev

from ..domain.formations import CATALOG
from ..domain.metrics import all_metrics
from ..domain.recipe import from_dict
from ..domain.styles import STYLES
from ..infrastructure.files import read_json, read_jsonl, write_json
from .generate_match import generate_from_recipe

OPPONENT = {"formation": "4-4-2", "style": "balanced", "level": 1.0}
COLUMNS = [("defensive_line_height", "def line (m)"), ("block_height_def", "block def (m)"),
           ("block_height_pos", "block poss (m)"), ("team_width_def", "width def (m)"),
           ("team_length_def", "length def (m)"), ("possession_pct", "poss %"),
           ("recoveries_opp_half_per_min", "recov opp half/min"), ("mean_pass_length_m", "pass len (m)")]


def configs(what):
    if what == "styles":
        return {s: dict(formation="4-4-2", style=s) for s in STYLES}
    return {f: dict(formation=f, style="balanced") for f in CATALOG}


def run_one(args):
    name, home, seed, steps = args
    recipe = from_dict({"mode": "full_match", "home": {**home, "level": 1.0}, "away": OPPONENT, "seed": seed})
    with tempfile.TemporaryDirectory() as tmp:
        out = generate_from_recipe(recipe, seed, tmp, render=False, steps=steps)[0]
        rows, ev = read_jsonl(os.path.join(out, "tracking.jsonl")), read_jsonl(os.path.join(out, "events.jsonl"))
        half = read_json(os.path.join(out, "meta.json"))["pitch"]["length_m"] / 2
    return name, all_metrics(rows, ev, "home", half)


def aggregate(results):
    """[(name, metrics)] -> {name: {metric: {mean, std, n}}}; seeds where a metric is undefined are skipped."""
    out = {}
    for name, m in results:
        for k, v in m.items():
            out.setdefault(name, {}).setdefault(k, []).append(v)
    return {name: {k: {"mean": mean(v), "std": pstdev(v), "n": len(v)} if (v := [x for x in vs if x is not None]) else None
                   for k, vs in ms.items()} for name, ms in out.items()}


def measure(what, seeds, steps, out_path):
    jobs = [(n, h, s, steps) for n, h in configs(what).items() for s in range(seeds)]
    with Pool(4, maxtasksperchild=1) as p:
        res = aggregate(p.map(run_one, jobs, chunksize=1))
    write_json(out_path, {"what": what, "seeds": seeds, "steps": steps, "results": res})
    return res


def table(title, data):
    head = "| config | " + " | ".join(h for _, h in COLUMNS) + " | n |"
    lines = [f"## {title}", "", f"Home team vs 4-4-2 balanced level 1.0, seeds 0..{data['seeds'] - 1}, {data['steps']} in-play steps each. Mean ± std across seeds.", "",
             head, "|" + "---|" * (len(COLUMNS) + 2)]
    for name, ms in data["results"].items():
        cells = [f"{ms[k]['mean']:.2f} ± {ms[k]['std']:.2f}" if ms[k] else "-" for k, _ in COLUMNS]
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {min(ms[k]['n'] for k, _ in COLUMNS if ms[k]) } |")
    return "\n".join(lines)


def write_doc(measure_dir, doc_path):
    parts = ["# Preset measurements", "",
             "Generated by `python -m tacticai.ingest measure`. Metrics are in engine metres, forward = toward the opponent goal, measured from the team's own goal line. Defending rows are those where the opponent owns the ball; loose-ball rows are excluded from phase metrics.", ""]
    for what in ("styles", "formations"):
        p = os.path.join(measure_dir, f"{what}.json")
        if os.path.exists(p):
            parts += [table(what.capitalize(), json.load(open(p))), ""]
    with open(doc_path, "w") as f:
        f.write("\n".join(parts))
